def mmss(t):
    t = int(t)
    return "%d:%02d" % (t // 60, t % 60)


def steps_html(key, items):
    marks = json.load(open(os.path.join(HERE, "videos", "oxlet-%s.steps.json" % key), encoding="utf-8"))
    assert len(marks) == len(items), (key, len(marks), len(items))
    rows = []
    for (title, desc), m in zip(items, marks):
        assert m["title"].split(":")[0].strip() in title or title in m["title"], (title, m["title"])
        rows.append(
            '<li><button type="button" class="step" data-v="%s" data-t="%.1f"><span class="tm">%s</span>'
            '<span class="tx"><b>%s</b><span>%s</span></span></button></li>'
            % (key, m["t"], mmss(m["t"]), html.escape(title), html.escape(desc)))
    return "\n".join(rows)


tpl = open(os.path.join(HERE, "guide_template.html"), encoding="utf-8").read()
page = tpl.replace("{{SELLER_STEPS}}", steps_html("seller", SELLER)).replace("{{ADMIN_STEPS}}", steps_html("admin", ADMIN))
open(os.path.join(HERE, "videos", "oxlet-guide.html"), "w", encoding="utf-8").write(page)
